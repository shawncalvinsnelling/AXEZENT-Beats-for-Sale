#!/usr/bin/env python3
"""Reproducible all-100 AXEZENT *composition* and rapper-vocal-space audit.

Audits exact MIDI note events generated by the existing 2 collection engines,
not protected commercial master recordings or subjective producer quality.
Never changes, re-renders, or republishes public audio.
"""
from __future__ import annotations
import argparse
import collections
import hashlib
import json
import math
import statistics
import tempfile
from pathlib import Path

from scripts.collection_two import load_collection_two, make_collection_two_catalog, ROOT
from scripts.render_arranged_review_audio import Arrangement, TICKS_BAR, TPQ, parse_key
from scripts.render_collection_two_review_audio import CollectionTwoArrangement, region_groove

CHANNEL_NAMES={0:"chords",1:"lead",2:"bass",3:"counter",9:"drums"}
DRUM_FAMILIES={
    "kick":{35,36},"snare":{37,38,39,40},"hat":{42,44,46,51,54,82}
}
KINDS={"intro","verse","hook","pre-hook","bridge","breakdown","outro"}

def verify_event_pairs(arr):
    active=collections.defaultdict(list)
    pairs=[]
    notes=sorted(arr.events,key=lambda r:(r[0],r[1],r[2].channel,r[2].note))
    stop=arr.spec["totalBars"]*TICKS_BAR
    for tick,priority,m in notes:
        if tick<0 or tick>stop:
            raise ValueError("MIDI event outside song "+arr.beat["id"])
        key=(m.channel,m.note)
        if m.type=="note_on" and m.velocity:
            active[key].append((tick,m.velocity))
        elif m.type=="note_off" or m.type=="note_on" and not m.velocity:
            if not active[key]:
                raise ValueError("Unpaired MIDI note-off "+arr.beat["id"])
            onset,velocity=active[key].pop(0)
            if tick<=onset:
                raise ValueError("Zero or negative note length "+arr.beat["id"])
            if m.channel in (0,1,2,3) and tick> (onset//TICKS_BAR+1)*TICKS_BAR:
                raise ValueError("Pitched note spills into next bar "+arr.beat["id"])
            pairs.append((onset,tick,m.channel,m.note,velocity))
    if any(active.values()):
        raise ValueError("Stuck MIDI notes in "+arr.beat["id"])
    return sorted(pairs)

def section_notes(notes,part):
    lower=part["startBar"]*TICKS_BAR
    upper=part["endBar"]*TICKS_BAR
    return [n for n in notes if lower<=n[0]<upper]

def hook_signature(notes,part):
    base=part["startBar"]*TICKS_BAR
    window=min(4,part["bars"])*TICKS_BAR
    return tuple(sorted((on-base,off-on,ch,p)
      for on,off,ch,p,v in notes if ch in (0,1,2,3) and base<=on<base+window))

def one(beat,plan,blueprint,temp):
    arr=Arrangement(beat,plan) if blueprint is None else CollectionTwoArrangement(beat,plan,blueprint)
    arr.build_midi(temp/"vocal-grid.mid")
    notes=verify_event_pairs(arr)
    hard=[]
    review=[]
    bpm=beat["bpm"]
    duration=240*plan["totalBars"]/bpm
    if abs(duration-plan["durationSeconds"])>.005:
        hard.append("Incorrect tempo/bar/second conversion")
    if abs(plan["totalBars"]-sum(s["bars"] for s in plan["sections"]))>0:
        hard.append("Song bars do not match section totals")
    root,scale=parse_key(beat["key"])
    allowed={(root+offset)%12 for offset in scale}
    wrong={n[3]%12 for n in notes if n[2] in (0,1,2,3)}-allowed
    if wrong:
        hard.append("Out-of-key pitched MIDI note(s): "+str(sorted(wrong)))
    hooks=[p for p in plan["sections"] if p["kind"]=="hook"]
    verses=[p for p in plan["sections"] if p["kind"]=="verse"]
    if len(hooks)<2 or len(verses)<2:
        hard.append("Less than two repeated hooks or verses")
    if not hooks or not verses:
        raise ValueError("No representative hook or verse "+beat["id"])
    signature=hook_signature(notes,hooks[0])
    if any(hook_signature(notes,p)!=signature for p in hooks[1:]):
        hard.append("Returning hook does not retain its first-four-bar notes")
    summary={}
    verse_hats=[]
    verse_kick=[]
    verse_snare=[]
    beat1_upper=0
    counter_verse=0
    over_bars=0
    for part in plan["sections"]:
        if part["kind"] not in KINDS:
            hard.append("Unrecognized section kind "+str(part["kind"]))
        ns=section_notes(notes,part)
        pitch=sum(n[2] in (0,1,2,3) for n in ns)
        drums=[n for n in ns if n[2]==9]
        family_counts={role:sum(n[3] in ids for n in drums)
            for role,ids in DRUM_FAMILIES.items()}
        if part["kind"]=="verse":
            for bar in range(part["startBar"],part["endBar"]):
                x=[n for n in ns if bar*TICKS_BAR<=n[0]<(bar+1)*TICKS_BAR]
                lyric_window=[
                  n for n in x if n[2] in (1,3) and
                  n[0]-bar*TICKS_BAR<2*TPQ]
                beat1_upper+=len(lyric_window)
                if lyric_window:
                    hard.append("Foreground lead/counter in first two vocal beats of verse bar "+str(bar))
                verse_hats.append(sum(n[2]==9 and n[3] in DRUM_FAMILIES["hat"] for n in x))
                verse_kick.append(sum(n[2]==9 and n[3] in DRUM_FAMILIES["kick"] for n in x))
                verse_snare.append(sum(n[2]==9 and n[3] in DRUM_FAMILIES["snare"] for n in x))
                counter_verse+=sum(n[2]==3 for n in x)
                if sum(n[2]!=9 for n in x)>14:
                    over_bars+=1
        key=part["kind"]
        row=summary.setdefault(key,{"bars":0,"pitch":0,"drums":0,
                                   "kick":0,"snare":0,"hat":0})
        row["bars"]+=part["bars"]
        row["pitch"]+=pitch
        row["drums"]+=len(drums)
        for role,num in family_counts.items():
            row[role]+=num
    if verse_kick and min(verse_kick)<1: hard.append("Verse bar without a kick")
    if verse_snare and min(verse_snare)<1: hard.append("Verse bar without a snare/clap")
    if verse_hats and min(verse_hats)<1: hard.append("Verse bar without top percussion")
    if over_bars: review.append(str(over_bars)+" verse bars have >14 pitched MIDI attacks")
    if not any(n[2]==1 for n in section_notes(notes,hooks[0])):
        hard.append("Hook contains no lead motif")
    if not any(n[2]==2 for n in section_notes(notes,verses[0])):
        hard.append("Verse contains no bass")
    if not any(n[2]==0 for n in section_notes(notes,verses[0])):
        hard.append("Verse contains no harmonic instrument")
    def per_bar(role,kind):
        row=summary.get(kind)
        return round(row[role]/row["bars"],3) if row else 0
    hook_pitch=per_bar("pitch","hook")
    verse_pitch=per_bar("pitch","verse")
    if verse_pitch>=hook_pitch:
        review.append("Verse pitch attacks as dense or denser than hook")
    groove_delta=[]
    for on,off,ch,p,v in notes:
        if ch!=9 or p not in DRUM_FAMILIES["kick"]:
            continue
        # Offset from nearest 1/16 beat in real physical milliseconds.
        offset_tick=(on+TPQ//8)%(TPQ//4)-TPQ//8
        groove_delta.append(offset_tick*60000/(bpm*TPQ))
    def fingerprint(kind):
        part=next(s for s in plan["sections"] if s["kind"]==kind)
        n=section_notes(notes,part)
        base=part["startBar"]*TICKS_BAR
        return hashlib.sha256(repr(tuple(sorted(
          (round((on-base)/120),ch,p) for on,off,ch,p,v in n
          if on<base+4*TICKS_BAR and ch in (1,2,9)
        ))).encode()).hexdigest()[:16]
    source=beat["collection"]
    return {
        "rank":beat["releaseRank"],"id":beat["id"],"title":beat["title"],
        "city":beat["city"],"state":beat["state"],"region":source,
        "bpm":bpm,"key":beat["key"],"groove":arr.groove,
        "sectionOrder":[p["label"] for p in plan["sections"]],
        "durationSeconds":round(duration,3),
        "totalBars":plan["totalBars"],"noteAttacks":len(notes),
        "drumAttacks":sum(n[2]==9 for n in notes),
        "hookLeadBassDrumFingerprint":fingerprint("hook"),
        "verseLeadBassDrumFingerprint":fingerprint("verse"),
        "firstTwoBeatsOfVerseLeadCounterAttacks":beat1_upper,
        "allVerseBarsKickPresent":bool(verse_kick and min(verse_kick)>=1),
        "allVerseBarsSnarePresent":bool(verse_snare and min(verse_snare)>=1),
        "allVerseBarsTopPercPresent":bool(verse_hats and min(verse_hats)>=1),
        "verseCounterNotes":counter_verse,
        "versePitchedAttacksPerBar":verse_pitch,
        "hookPitchedAttacksPerBar":hook_pitch,
        "verseKickPerBar":per_bar("kick","verse"),
        "verseSnarePerBar":per_bar("snare","verse"),
        "verseHatPerBar":per_bar("hat","verse"),
        "hookKickPerBar":per_bar("kick","hook"),
        "hookSnarePerBar":per_bar("snare","hook"),
        "hookHatPerBar":per_bar("hat","hook"),
        "kickSixteenthTimingErrorRmsMs":round(math.sqrt(
          statistics.mean(x*x for x in groove_delta)),3) if groove_delta else None,
        "hardFailures":list(dict.fromkeys(hard)),
        "reviewFlags":list(dict.fromkeys(review)),
    }

def main():
    ap=argparse.ArgumentParser()
    ap.add_argument("--out",type=Path,required=True)
    args=ap.parse_args()
    catalog=json.loads((ROOT/"data/catalog.json").read_text("utf-8"))
    old=json.loads((ROOT/"data/arrangements.json").read_text("utf-8"))
    allcatalog,plans=make_collection_two_catalog(catalog,old)
    songs=sorted((b for b in allcatalog if isinstance(b.get("releaseRank"),int)
        and 1<=b["releaseRank"]<=100),key=lambda b:b["releaseRank"])
    blueprints={x["id"]:x for x in load_collection_two()}
    if len(songs)!=100 or len(plans)!=100:
        raise ValueError("Exactly 100 regional arrangements required")
    records=[]
    with tempfile.TemporaryDirectory() as tmp:
        for beat in songs:
            plan=plans[beat["id"]]
            rec=one(beat,plan,blueprints.get(beat["id"]),Path(tmp))
            records.append(rec)
    failures=[x for x in records if x["hardFailures"]]
    review=[x for x in records if x["reviewFlags"]]
    metrics={
        "songsAudited":100,
        "firstCollectionPreserved":50,
        "newCollectionAudited":50,
        "cities":len({(x["city"],x["state"]) for x in records}),
        "totalSongBars":sum(x["totalBars"] for x in records),
        "totalMIDIStartEvents":sum(x["noteAttacks"] for x in records),
        "uniqueHookLeadBassDrumGrids":len({x["hookLeadBassDrumFingerprint"] for x in records}),
        "uniqueVerseLeadBassDrumGrids":len({x["verseLeadBassDrumFingerprint"] for x in records}),
        "zeroLeadOrCounterVocalPickups":sum(x["firstTwoBeatsOfVerseLeadCounterAttacks"]==0 for x in records),
        "allVerseBarsContainKickSnareAndTopPerc":sum(
          x["allVerseBarsKickPresent"] and x["allVerseBarsSnarePresent"]
          and x["allVerseBarsTopPercPresent"] for x in records),
        "meanVersePitchAttacksPerBar":round(statistics.mean(
          x["versePitchedAttacksPerBar"] for x in records),2),
        "meanHookPitchAttacksPerBar":round(statistics.mean(
          x["hookPitchedAttacksPerBar"] for x in records),2),
        "averageKickGridTimingDeviationMs":round(statistics.mean(
          x["kickSixteenthTimingErrorRmsMs"] for x in records),3),
        "hardFailureCount":len(failures),
        "artisticReviewTrackCount":len(review),
        "source":"100 deterministic original MIDI performances, not reference commercial tracks, listening-based vocal tests or artist-approved masters"
    }
    args.out.mkdir(parents=True,exist_ok=True)
    (args.out/"AXEZENT_100_RAP_GRID_AUDIT.json").write_text(
      json.dumps({"summary":metrics,"tracks":records},indent=2,ensure_ascii=False)+"\n",encoding="utf-8")
    lines=[
      "# AXEZENT — All 100 Beats: Rap-Vocal-Readiness MIDI Audit",
      "",
      "Audited the exact original generated MIDI-note events for all 100 songs;",
      "no commercial recording was transcribed or any public audio changed.",
      "",
      "## Summary",
      "",
      *[f"- **{k}:** {v}" for k,v in metrics.items()],
      "",
      "## Every song: bars, drums, lead space and hook contrast",
      "",
      "| Rank | City | Title | BPM | Bars | Verse kick/snare/hat per bar | Verse pitched attacks/bar | Hook pitched attacks/bar | Timing RMS ms | Findings |",
      "|---:|---|---|---:|---:|---:|---:|---:|---:|---|"
    ]
    for r in records:
        line=f'| {r["rank"]} | {r["city"]} | {r["title"].replace("|","/")} | {r["bpm"]} | {r["totalBars"]} | '
        drums=f'{r["verseKickPerBar"]}/{r["verseSnarePerBar"]}/{r["verseHatPerBar"]}'
        flags="; ".join(r["hardFailures"]+r["reviewFlags"]) or "No grid flags"
        lines.append(line+f'{drums} | {r["versePitchedAttacksPerBar"]} | {r["hookPitchedAttacksPerBar"]} | {r["kickSixteenthTimingErrorRmsMs"]} | {flags} |')
    lines += ["","## Scope and limits","",
      "Passing MIDI grid checks does NOT prove that lyrics flow naturally, drums sound like a real kit,",
      "loudness has been artist-approved, or that a song is a hit. Those need vocal performance,",
      "songwriting, speaker/room listening, mixing and appropriately licensed reference work.",
      "General MIDI SoundFont is a musical demo source, not a set of separate professional",
      "studio multitracks. Timing RMS here measures deviation from a theoretical 1/16-beat",
      "grid, not evidence of a special proprietary nanosecond/nanogap psychoacoustic method."]
    (args.out/"AXEZENT_100_RAP_GRID_AUDIT.md").write_text("\n".join(lines)+"\n",encoding="utf-8")
    print("RAP_GRID_SUMMARY:",json.dumps(metrics),flush=True)
    if failures:
        raise ValueError("Hard structural problems in "+str(len(failures))+" songs")
    print("PASS: 100 original song MIDI arrangements, unique cities and safe vocal entries.")

if __name__=="__main__":
    main()
